    Navigator.push(
      context,
      MaterialPageRoute(
        builder:
            (_) => _StudentClassSessionsScreen(
              api: widget.api,
              classRoom: c,
              session: widget.session,
            ),
      ),
    ).then((_) => _loadData());
  }

