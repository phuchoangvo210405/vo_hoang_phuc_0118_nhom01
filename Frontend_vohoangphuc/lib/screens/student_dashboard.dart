  List<SubjectModel> _subjects = [];
  Set<int> _leaveIdsWithRealEvidence = {};

  @override
  void initState() {
    super.initState();
    _loadData();
  }

  Future<void> _loadData() async {
    setState(() => _loading = true);
    try {
      final results = await Future.wait([
        widget.api.getClasses(),
        widget.api.getMyLeaveRequests(),
        widget.api.getSubjects(),
      ]);
      final leaves = results[1] as List<LeaveRequestModel>;
      final validEvidenceIds = <int>{};
      await Future.wait(
        leaves.map((l) async {
          try {
            final bytes = await widget.api.getLeaveEvidence(l.id);
            if (bytes.isNotEmpty &&
                !StampGenerator.isAutoGeneratedStampPng(bytes)) {
              validEvidenceIds.add(l.id);
            }
          } catch (_) {
            // Đơn không đính kèm ảnh minh chứng (404)
          }
        }),
      );
      if (!mounted) return;
      setState(() {
        _classes = results[0] as List<ClassRoomModel>;
        _myLeaves = leaves;
        _subjects = results[2] as List<SubjectModel>;
        _leaveIdsWithRealEvidence = validEvidenceIds;
      });
    } catch (e) {
      if (!mounted) return;
      showAppSnackBar(context, e.toString(), isError: true);
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

