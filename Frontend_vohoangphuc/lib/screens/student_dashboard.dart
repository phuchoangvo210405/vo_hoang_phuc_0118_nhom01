class _StudentClassSessionsScreen extends StatefulWidget {
  final ApiClient api;
  final ClassRoomModel classRoom;
  final AuthSession session;

  const _StudentClassSessionsScreen({
    required this.api,
    required this.classRoom,
    required this.session,
  });

  @override
  State<_StudentClassSessionsScreen> createState() =>
      _StudentClassSessionsScreenState();
}

class _StudentClassSessionsScreenState
    extends State<_StudentClassSessionsScreen> {
  bool _loading = true;
  List<ClassSessionModel> _sessions = [];

  @override
  void initState() {
    super.initState();
    _loadSessions();
  }

  Future<void> _loadSessions() async {
    setState(() => _loading = true);
    try {
      final list = await widget.api.getClassSessions(widget.classRoom.id);
      if (!mounted) return;
      setState(() => _sessions = list);
    } catch (e) {
      if (!mounted) return;
      showAppSnackBar(context, e.toString(), isError: true);
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  Future<void> _showCheckInDialog(ClassSessionModel s) async {
    final qrCtrl = TextEditingController();
    bool cameraOpen = false;
    MobileScannerController? scannerCtrl;

    final ok = await showDialog<bool>(
      context: context,
      builder:
          (ctx) => StatefulBuilder(
            builder:
                (ctx, setModalState) => AlertDialog(
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(20),
                  ),
                  title: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      const Text(
                        'Điểm danh Buổi học',
                        style: TextStyle(
                          fontSize: 17,
                          fontWeight: FontWeight.bold,
                        ),
                      ),
                      Text(
                        s.title,
                        style: const TextStyle(
                          fontSize: 13,
                          color: Color(0xFF047857),
                        ),
                      ),
                    ],
                  ),
                  content: SingleChildScrollView(
                    child: SizedBox(
                      width: 360,
                      child: Column(
                        mainAxisSize: MainAxisSize.min,
                        crossAxisAlignment: CrossAxisAlignment.stretch,
                        children: [
                          Row(
                            children: [
                              Expanded(
                                child: FilledButton.icon(
                                  style: FilledButton.styleFrom(
                                    backgroundColor:
                                        cameraOpen
                                            ? const Color(0xFFDC2626)
                                            : const Color(0xFF4F46E5),
                                  ),
                                  onPressed: () {
                                    setModalState(() {
                                      cameraOpen = !cameraOpen;
                                      if (cameraOpen) {
                                        scannerCtrl ??= MobileScannerController(
                                          detectionSpeed: DetectionSpeed.normal,
                                          facing: CameraFacing.back,
                                        );
                                      } else {
                                        scannerCtrl?.dispose();
                                        scannerCtrl = null;
                                      }
                                    });
                                  },
                                  icon: Icon(
                                    cameraOpen
                                        ? Icons.videocam_off_rounded
                                        : Icons.qr_code_scanner_rounded,
                                    size: 18,
                                  ),
                                  label: Text(
                                    cameraOpen
                                        ? 'Tắt Camera'
                                        : 'Bật Camera quét QR',
                                    style: const TextStyle(fontSize: 12.5),
                                  ),
                                ),
                              ),
                              const SizedBox(width: 8),
                              OutlinedButton.icon(
                                onPressed: () async {
                                  final picked = await ImagePicker().pickImage(
                                    source: ImageSource.gallery,
                                  );
                                  if (picked == null) return;
                                  final temp = MobileScannerController();
                                  try {
                                    final cap = await temp.analyzeImage(
                                      picked.path,
                                    );
                                    if (cap != null &&
                                        cap.barcodes.isNotEmpty &&
                                        cap.barcodes.first.rawValue != null) {
                                      qrCtrl.text =
                                          cap.barcodes.first.rawValue!.trim();
                                    }
                                  } finally {
                                    await temp.dispose();
                                  }
                                },
                                icon: const Icon(
                                  Icons.photo_library_outlined,
                                  size: 17,
                                ),
                                label: const Text(
                                  'Ảnh QR',
                                  style: TextStyle(fontSize: 12.5),
                                ),
                              ),
                            ],
                          ),
                          if (cameraOpen && scannerCtrl != null) ...[
                            const SizedBox(height: 12),
                            ClipRRect(
                              borderRadius: BorderRadius.circular(14),
                              child: SizedBox(
                                height: 210,
                                child: MobileScanner(
                                  controller: scannerCtrl!,
                                  onDetect: (capture) {
                                    for (final b in capture.barcodes) {
                                      final raw = b.rawValue;
                                      if (raw != null &&
                                          raw.trim().isNotEmpty) {
                                        HapticFeedback.mediumImpact();
                                        qrCtrl.text = raw.trim();
                                        scannerCtrl?.dispose();
                                        scannerCtrl = null;
                                        Navigator.pop(ctx, true);
                                        break;
                                      }
                                    }
                                  },
                                ),
                              ),
                            ),
                          ],
                          const SizedBox(height: 12),
                          TextField(
                            controller: qrCtrl,
                            decoration: InputDecoration(
                              labelText: 'Nhập mã QR / Barcode điểm danh',
                              hintText: 'Quét camera hoặc nhập mã tại đây...',
                              prefixIcon: const Icon(Icons.qr_code_rounded),
                              suffixIcon: IconButton(
                                tooltip: 'Dán từ bộ nhớ tạm',
                                icon: const Icon(Icons.content_paste_rounded),
                                onPressed: () async {
                                  final data = await Clipboard.getData(
                                    Clipboard.kTextPlain,
                                  );
                                  if (data?.text != null) {
                                    qrCtrl.text = data!.text!.trim();
                                  }
                                },
                              ),
                            ),
                          ),
                        ],
                      ),
                    ),
                  ),
                  actions: [
                    TextButton(
                      onPressed: () {
                        scannerCtrl?.dispose();
                        Navigator.pop(ctx, false);
                      },
                      child: const Text('Huỷ'),
                    ),
                    FilledButton.icon(
                      style: FilledButton.styleFrom(
                        backgroundColor: const Color(0xFF047857),
                      ),
                      icon: const Icon(Icons.how_to_reg_rounded),
                      label: const Text('Điểm danh'),
                      onPressed: () {
                        scannerCtrl?.dispose();
                        Navigator.pop(ctx, true);
                      },
                    ),
                  ],
                ),
          ),
    );

    if (ok != true) return;
    final qr = qrCtrl.text.trim();
    if (qr.isEmpty) {
      if (!mounted) return;
      showAppSnackBar(
        context,
        'Vui lòng quét mã QR hoặc nhập mã Barcode điểm danh.',
        isError: true,
      );
      return;
    }

    // Tự động lấy vị trí GPS thực tế của điện thoại để kiểm tra phạm vi lớp học
    double lat = s.latitude;
    double lon = s.longitude;
    try {
      final serviceEnabled = await Geolocator.isLocationServiceEnabled();
      if (!serviceEnabled) {
        if (!mounted) return;
        showAppSnackBar(
          context,
          'Vui lòng bật Định vị (GPS) trên điện thoại để điểm danh.',
          isError: true,
        );
        return;
      }
      var perm = await Geolocator.checkPermission();
      if (perm == LocationPermission.denied) {
        perm = await Geolocator.requestPermission();
      }
      if (perm == LocationPermission.denied ||
          perm == LocationPermission.deniedForever) {
        if (!mounted) return;
        showAppSnackBar(
          context,
          'Vui lòng cấp quyền Vị trí (GPS) để kiểm tra phạm vi lớp học.',
          isError: true,
        );
        return;
      }

      final pos = await Geolocator.getCurrentPosition(
        locationSettings: const LocationSettings(
          accuracy: LocationAccuracy.high,
        ),
      );
      lat = pos.latitude;
      lon = pos.longitude;

      // Nếu buổi học có cài đặt tọa độ phòng học (khác 0,0), kiểm tra khoảng cách trước
      if (s.latitude != 0.0 || s.longitude != 0.0) {
        final distMeters = Geolocator.distanceBetween(
          lat,
          lon,
          s.latitude,
          s.longitude,
        );
        final allowedRadius = s.radiusMeters > 0 ? s.radiusMeters : 100.0;
        if (distMeters > allowedRadius) {
          if (!mounted) return;
          final outMsg =
              'Bạn đang ở ngoài khu vực lớp học (Cách lớp ${distMeters.round()} mét)';
          showAppSnackBar(context, outMsg, isError: true);
          await showDialog<void>(
            context: context,
            builder:
                (dCtx) => AlertDialog(
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(20),
                  ),
                  title: const Row(
                    children: [
                      Icon(
                        Icons.location_off_rounded,
                        color: Color(0xFFDC2626),
                      ),
                      SizedBox(width: 8),
                      Expanded(
                        child: Text(
                          'Ngoài phạm vi điểm danh',
                          style: TextStyle(
                            fontSize: 16.5,
                            fontWeight: FontWeight.bold,
                            color: Color(0xFF991B1B),
                          ),
                        ),
                      ),
                    ],
                  ),
                  content: Text(
                    '$outMsg.\nPhạm vi cho phép của buổi học là ${allowedRadius.round()} mét.',
                    style: const TextStyle(fontSize: 13.5, height: 1.4),
                  ),
                  actions: [
                    FilledButton(
                      onPressed: () => Navigator.pop(dCtx),
                      child: const Text('Đã hiểu'),
                    ),
                  ],
                ),
          );
          return;
        }
      }
    } catch (e) {
      if (!mounted) return;
      showAppSnackBar(
        context,
        'Không thể xác định vị trí GPS: $e',
        isError: true,
      );
      return;
    }

    try {
      final photoBytes = await StampGenerator.generateEvidencePng(
        header: 'XÁC THỰC ĐIỂM DANH SINH VIÊN',
        studentName:
            '${widget.session.fullName} (@${widget.session.username})',
        subtitle: '${widget.classRoom.name} • ${s.title}',
        detailLine1:
            'Toạ độ GPS: (${lat.toStringAsFixed(5)}, ${lon.toStringAsFixed(5)})',
        detailLine2: 'Mã QR: $qr',
        accentColor: const Color(0xFF047857),
      );

      final msg = await widget.api.checkInSession(
        s.id,
        qrToken: qr,
        latitude: lat,
        longitude: lon,
        photoBytes: photoBytes,
        photoFileName: 'attendance_${s.id}.png',
      );
      if (!mounted) return;
      showAppSnackBar(context, msg);
    } catch (e) {
      if (!mounted) return;
      showAppSnackBar(context, e.toString(), isError: true);
    }
  }

