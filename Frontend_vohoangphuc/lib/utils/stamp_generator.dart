import 'dart:typed_data';
import 'dart:ui' as ui;
import 'package:flutter/material.dart';

class StampGenerator {
  /// Tạo ảnh PNG minh chứng điểm danh hoặc đơn xin nghỉ trực tiếp trên máy ảo Android
  static Future<Uint8List> generateEvidencePng({
    required String header,
    required String studentName,
    required String subtitle,
    required String detailLine1,
    required String detailLine2,
    Color accentColor = const Color(0xFF4F46E5),
  }) async {
    const double width = 640;
    const double height = 380;
    final recorder = ui.PictureRecorder();
    final canvas = Canvas(recorder, const Rect.fromLTWH(0, 0, width, height));

    // Background
    final bgPaint = Paint()..color = const Color(0xFFF8FAFC);
    canvas.drawRect(const Rect.fromLTWH(0, 0, width, height), bgPaint);

    // Top Accent Banner
    final bannerPaint = Paint()..color = accentColor;
    canvas.drawRect(const Rect.fromLTWH(0, 0, width, 86), bannerPaint);

    // Border
    final borderPaint =
        Paint()
          ..color = accentColor.withValues(alpha: 0.35)
          ..style = PaintingStyle.stroke
          ..strokeWidth = 6;
    canvas.drawRect(
      const Rect.fromLTWH(3, 3, width - 6, height - 6),
      borderPaint,
    );

    void drawText(
      String text,
      Offset offset, {
      double fontSize = 20,
      FontWeight fontWeight = FontWeight.normal,
      Color color = const Color(0xFF1E293B),
      double maxWidth = 580,
    }) {
      final tp = TextPainter(
        text: TextSpan(
          text: text,
          style: TextStyle(
            fontSize: fontSize,
            fontWeight: fontWeight,
            color: color,
          ),
        ),
        textDirection: TextDirection.ltr,
        maxLines: 2,
        ellipsis: '...',
      )..layout(maxWidth: maxWidth);
      tp.paint(canvas, offset);
    }

    drawText(
      header.toUpperCase(),
      const Offset(28, 26),
      fontSize: 24,
      fontWeight: FontWeight.bold,
      color: Colors.white,
    );

    drawText(
      'Sinh viên: $studentName',
      const Offset(28, 112),
      fontSize: 24,
      fontWeight: FontWeight.w700,
      color: const Color(0xFF0F172A),
    );

    drawText(
      subtitle,
      const Offset(28, 156),
      fontSize: 20,
      fontWeight: FontWeight.w600,
      color: accentColor,
    );

    drawText(
      detailLine1,
      const Offset(28, 204),
      fontSize: 18,
      color: const Color(0xFF334155),
    );

    drawText(
      detailLine2,
      const Offset(28, 250),
      fontSize: 18,
      color: const Color(0xFF334155),
    );

    final now = DateTime.now();
    final timeStr =
        '${now.day.toString().padLeft(2, '0')}/${now.month.toString().padLeft(2, '0')}/${now.year} '
        '${now.hour.toString().padLeft(2, '0')}:${now.minute.toString().padLeft(2, '0')}:${now.second.toString().padLeft(2, '0')}';

    drawText(
      'Xác thực hệ thống Điểm Danh SV - Nhóm 01 • $timeStr',
      const Offset(28, 326),
      fontSize: 15,
      fontWeight: FontWeight.w500,
      color: const Color(0xFF64748B),
    );

    // Stamp seal circle on the right
    final sealPaint =
        Paint()
          ..color = accentColor.withValues(alpha: 0.14)
          ..style = PaintingStyle.fill;
    canvas.drawCircle(const Offset(540, 220), 62, sealPaint);
    final sealBorder =
        Paint()
          ..color = accentColor
          ..style = PaintingStyle.stroke
          ..strokeWidth = 3;
    canvas.drawCircle(const Offset(540, 220), 62, sealBorder);
    drawText(
      'ĐÃ GỬI HỆ THỐNG',
      const Offset(484, 210),
      fontSize: 13.5,
      fontWeight: FontWeight.bold,
      color: accentColor,
      maxWidth: 125,
    );

    final picture = recorder.endRecording();
    final img = await picture.toImage(width.toInt(), height.toInt());
    final byteData = await img.toByteData(format: ui.ImageByteFormat.png);
    return byteData!.buffer.asUint8List();
  }

  /// Kiểm tra xem mảng byte ảnh có phải là ảnh mẫu tự sinh (640x380) trước đây hay không
  static bool isAutoGeneratedStampPng(Uint8List bytes) {
    if (bytes.length < 24) return false;
    // Kiểm tra header PNG: 89 50 4E 47
    if (bytes[0] != 0x89 ||
        bytes[1] != 0x50 ||
        bytes[2] != 0x4E ||
        bytes[3] != 0x47) {
      return false;
    }
    final width =
        (bytes[16] << 24) | (bytes[17] << 16) | (bytes[18] << 8) | bytes[19];
    final height =
        (bytes[20] << 24) | (bytes[21] << 16) | (bytes[22] << 8) | bytes[23];
    return width == 640 && height == 380;
  }
}

/// Widget hiển thị biểu tượng ma trận QR trực quan từ chuỗi QrToken của buổi học
class QrMatrixPreview extends StatelessWidget {
  final String token;
  final double size;

  const QrMatrixPreview({super.key, required this.token, this.size = 160});

  @override
  Widget build(BuildContext context) {
    return Container(
      width: size,
      height: size,
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: const Color(0xFFE2E8F0), width: 2),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.06),
            blurRadius: 12,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: CustomPaint(painter: _QrMatrixPainter(token)),
    );
  }
}

class _QrMatrixPainter extends CustomPainter {
  final String token;

  _QrMatrixPainter(this.token);

  @override
  void paint(Canvas canvas, Size size) {
    const int grid = 15;
    final cell = size.width / grid;
    final paint =
        Paint()
          ..color = const Color(0xFF0F172A)
          ..style = PaintingStyle.fill;

    void drawFinder(int r0, int c0) {
      for (int r = 0; r < 5; r++) {
        for (int c = 0; c < 5; c++) {
          final isBorder = r == 0 || r == 4 || c == 0 || c == 4;
          final isCenter = r >= 1 && r <= 3 && c >= 1 && c <= 3 && (r == 2 && c == 2);
          if (isBorder || isCenter) {
            canvas.drawRect(
              Rect.fromLTWH((c0 + c) * cell, (r0 + r) * cell, cell, cell),
              paint,
            );
          }
        }
      }
    }

    drawFinder(0, 0);
    drawFinder(0, grid - 5);
    drawFinder(grid - 5, 0);

    final bytes = token.codeUnits;
    int idx = 0;
    for (int r = 0; r < grid; r++) {
      for (int c = 0; c < grid; c++) {
        final inTopLeft = r < 6 && c < 6;
        final inTopRight = r < 6 && c >= grid - 6;
        final inBottomLeft = r >= grid - 6 && c < 6;
        if (inTopLeft || inTopRight || inBottomLeft) continue;

        final code = bytes.isEmpty ? (r * 31 + c) : bytes[idx % bytes.length];
        final bit = ((code + r * 7 + c * 13) % 3) != 0;
        idx++;
        if (bit) {
          canvas.drawRect(
            Rect.fromLTWH(c * cell, r * cell, cell * 0.92, cell * 0.92),
            paint,
          );
        }
      }
    }
  }

  @override
  bool shouldRepaint(covariant _QrMatrixPainter oldDelegate) =>
      oldDelegate.token != token;
}
